import { readFile, writeFile } from 'node:fs/promises';
import { inflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';

// The extension is the source of truth for the bitmap, geometry and animation.
// Generate a self-contained npm artifact without chrome.runtime or image requests.
const extension = new URL('../../../apps/chrome-extension/', import.meta.url);
const source = await readFile(new URL('content-cursor.js', extension), 'utf8');
const png = await readFile(new URL('images/cursor-chat.png', extension));
const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
if (png.subarray(0,8).toString('hex') !== '89504e470d0a1a0a' || png[24] !== 8 || png[25] !== 6 || png[28] !== 0) throw new Error('Cursor asset must be a noninterlaced RGBA8 PNG');
const chunks = [];
for (let offset = 8; offset < png.length;) {
  const length = png.readUInt32BE(offset), type = png.subarray(offset+4,offset+8).toString();
  if (type === 'IDAT') chunks.push(png.subarray(offset+8,offset+8+length));
  offset += length + 12;
}
const scanlines = inflateSync(Buffer.concat(chunks)), stride = width * 4;
if (scanlines.length !== (stride+1)*height) throw new Error('Invalid cursor bitmap');
const pixels = Buffer.alloc(stride*height);
function paeth(a,b,c) {
  const p=a+b-c, pa=Math.abs(p-a), pb=Math.abs(p-b), pc=Math.abs(p-c);
  return pa<=pb && pa<=pc ? a : pb<=pc ? b : c;
}
for (let y=0;y<height;y++) {
  const filter=scanlines[y*(stride+1)];
  if (filter>4) throw new Error('Invalid PNG filter');
  for (let x=0;x<stride;x++) {
    const at=y*stride+x, a=x>=4?pixels[at-4]:0, b=y?pixels[at-stride]:0, c=y && x>=4?pixels[at-stride-4]:0;
    const predictor=[0,a,b,Math.floor((a+b)/2),paeth(a,b,c)][filter];
    pixels[at]=(scanlines[y*(stride+1)+1+x]+predictor)&255;
  }
}
const marker='const BASE_ROTATION = -44;';
const start=source.indexOf(marker);
if (start<0 || source.split('document.createElement("img")').length!==2) throw new Error('Cursor renderer changed: review extraction');
const defaults=['DEFAULT_X_RATIO','DEFAULT_Y_RATIO'].map(name=>{
  const match=source.match(new RegExp(`const ${name} = [0-9.]+;`));
  if (!match) throw new Error(`Missing ${name}`);
  return match[0];
}).join('\n');
// Canvas retains the exact original pixels under sites with img-src 'none'.
// All motion, sizing, offsets and rotations remain the extension's own code.
const renderer=defaults+'\n'+source.slice(start).replace('document.createElement("img")','document.createElement("canvas")');
const fingerprint=createHash('sha256').update(source).update(png).digest('hex');
const output=`// Generated by scripts/generate-cursor.mjs from the Chrome cursor. Do not edit.\nexport const cursorFingerprint = ${JSON.stringify(fingerprint)};\nexport const cursorSource: string = ${JSON.stringify(renderer)};\nexport const cursorBitmap = ${JSON.stringify({width,height,rgba:pixels.toString('base64')})};\n`;
const target=new URL('../src/cursor.generated.ts',import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8')!==output) throw new Error('Cursor artifact is stale: run node scripts/generate-cursor.mjs');
} else await writeFile(target,output);
